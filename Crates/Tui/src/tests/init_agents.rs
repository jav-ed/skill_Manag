#[test]
fn no_file_is_made_when_no_skill_could_be_installed() {
    let world = world();
    world.vault_file("project-files/AGENTS.md", "# Mine\n");
    // In the vault but not in git: the plan for it fails, so nothing can be installed.
    world.vault_file("fresh/SKILL.md", "untracked");
    let mut ui = Harness::new(world);
    to_the_skills_page(&mut ui);
    // No doc-start in this vault, so no scaffold; untick the mandatory skills, tick the one that cannot be planned.
    ui.press('d');
    ui.press('a').press('a');
    ui.press('j').press('j').press(' ');

    ui.code(Code::Enter).wait_done();

    assert!(ui.screen().contains("failed"), "{}", ui.screen());
    assert!(
        !ui.world.exists("projects/fresh"),
        "the folder was taken back"
    );
    assert!(!ui.world.exists(FILE));
}
