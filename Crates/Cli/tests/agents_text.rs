//! The text the projects share: `agents seed`, where the vault keeps it, and the note at the end of the block.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::indexing_slicing)]
mod common;

use common::{json_of, skillmirror};
use predicates::prelude::PredicateBooleanExt;
use predicates::str::contains;
use skillmirror_testkit::World;

const END: &str = "<!-- skillmirror:autogenerated end -->";

/// The standard world whose vault also has the three skills the built-in text names, all mandatory.
fn world() -> World {
    let world = World::standard();
    world
        .vault_file("doc-start/SKILL.md", "doc-start v1")
        .vault_file("file-tree-optimization/SKILL.md", "ftree v1")
        .vault_config(&["coding", "tmux", "doc-start", "file-tree-optimization"])
        .commit_vault();
    world
}

fn project(world: &World, name: &str) -> std::path::PathBuf {
    world.root().join(name)
}

// ---- seed ---------------------------------------------------------------------------------------------

#[test]
fn seed_writes_the_built_in_text_into_the_vault_folder_and_says_what_comes_next() {
    let world = world();

    skillmirror(&world)
        .args(["agents", "seed"])
        .assert()
        .success()
        .stdout(contains("Wrote the built-in text to"))
        .stdout(contains("project-files/AGENTS.md"))
        .stdout(contains("agents sync"));

    let text = world.read("vault/project-files/AGENTS.md");
    assert!(text.starts_with("# Coding related\n"), "{text}");
    assert!(text.ends_with('\n') && !text.contains("skillmirror:autogenerated"));
}

#[test]
fn after_seeding_the_vault_text_is_the_source_and_every_project_is_still_in_step() {
    let world = world();
    let fresh = project(&world, "fresh");
    skillmirror(&world)
        .arg("init")
        .arg(&fresh)
        .arg("--yes")
        .assert()
        .success();

    skillmirror(&world)
        .args(["agents", "seed"])
        .assert()
        .success();

    // The same words, now read from the vault: the blocks already hold them.
    skillmirror(&world)
        .args(["agents", "status", "--project"])
        .arg(&fresh)
        .assert()
        .success()
        .stdout(contains("project-files/AGENTS.md"))
        .stdout(contains("current"));
}

#[test]
fn seed_never_overwrites_a_text_that_is_there() {
    let world = world();
    world.vault_file("project-files/AGENTS.md", "# My own rules\n");

    skillmirror(&world)
        .args(["agents", "seed"])
        .assert()
        .code(3)
        .stderr(contains("project-files/AGENTS.md already exists"))
        .stderr(contains("agents sync"));

    assert_eq!(
        world.read("vault/project-files/AGENTS.md"),
        "# My own rules\n"
    );
}

#[test]
fn seed_dry_run_names_the_file_and_writes_nothing() {
    let world = world();

    skillmirror(&world)
        .args(["agents", "seed", "--dry-run"])
        .assert()
        .success()
        .stdout(contains("Would write the built-in text to"))
        .stdout(contains("project-files/AGENTS.md"));

    assert!(!world.exists("vault/project-files"));
}

#[test]
fn seed_dry_run_refuses_for_the_same_reason_the_real_run_does() {
    let world = world();
    world.vault_file("project-files/AGENTS.md", "x");

    skillmirror(&world)
        .args(["agents", "seed", "--dry-run"])
        .assert()
        .code(3)
        .stderr(contains("already exists"));
}

#[test]
fn seed_json_is_one_document() {
    let world = world();

    let document = json_of(skillmirror(&world).args(["agents", "seed", "--json"]));

    assert_eq!(document["command"], "agents seed");
    assert_eq!(document["dry_run"], false);
    assert!(
        document["path"]
            .as_str()
            .unwrap()
            .ends_with("project-files/AGENTS.md")
    );
    assert!(world.exists("vault/project-files/AGENTS.md"));
}

