// ---- the note at the end of the block -----------------------------------------------------------------

#[test]
fn a_new_file_ends_its_block_with_the_note_about_what_may_be_changed() {
    let world = world();
    let fresh = project(&world, "fresh");

    skillmirror(&world)
        .arg("init")
        .arg(&fresh)
        .arg("--yes")
        .assert()
        .success();

    let text = std::fs::read_to_string(fresh.join("AGENTS.md")).unwrap();
    let before_end = text.strip_suffix(&format!("{END}\n")).unwrap();
    assert!(
        before_end.ends_with("please change only what comes below it.*\n"),
        "{text}"
    );
    assert!(before_end.contains("\n---\n\n*Managed by skillmirror."));
}

#[test]
fn the_note_stays_when_the_vault_text_changes_and_what_is_below_it_is_left_alone() {
    let world = world();
    world.vault_file("project-files/AGENTS.md", "# Rules\n\n1. old\n");
    world.commit_vault();
    let one = project(&world, "one");
    skillmirror(&world)
        .args(["agents", "add", "--yes", "--project"])
        .arg(&one)
        .assert()
        .success();
    let mut mine = std::fs::read_to_string(one.join("AGENTS.md")).unwrap();
    mine.push_str("\n## This project\n\nOnly runs on Linux.\n");
    std::fs::write(one.join("AGENTS.md"), &mine).unwrap();

    world.vault_file("project-files/AGENTS.md", "# Rules\n\n1. new\n");
    skillmirror(&world)
        .args(["agents", "sync", "--yes", "--project"])
        .arg(&one)
        .assert()
        .success();

    let now = std::fs::read_to_string(one.join("AGENTS.md")).unwrap();
    assert!(now.contains("1. new") && !now.contains("1. old"), "{now}");
    assert!(now.contains("*Managed by skillmirror."), "{now}");
    assert!(
        now.ends_with("\n## This project\n\nOnly runs on Linux.\n"),
        "{now}"
    );
}

// ---- the line `status` adds ----------------------------------------------------------------------------

/// A world with a project whose block was written from "old", then a vault text that says "new".
fn world_behind(edit_block_by_hand: bool) -> World {
    let world = world();
    world.vault_file("project-files/AGENTS.md", "# Rules\n\n1. old\n");
    world.commit_vault();
    let one = project(&world, "one");
    skillmirror(&world)
        .args(["agents", "add", "--yes", "--project"])
        .arg(&one)
        .assert()
        .success();
    if edit_block_by_hand {
        let text = std::fs::read_to_string(one.join("AGENTS.md")).unwrap();
        std::fs::write(one.join("AGENTS.md"), text.replace("1. old", "1. mine")).unwrap();
    }
    world.vault_file("project-files/AGENTS.md", "# Rules\n\n1. new\n");
    world
}

#[test]
fn status_says_how_many_blocks_are_behind_the_text_and_what_to_run() {
    let world = world_behind(false);

    skillmirror(&world)
        .arg("status")
        .assert()
        .stdout(contains("AGENTS.md blocks: 1 out of date."))
        .stdout(contains("agents sync"));
}

#[test]
fn status_names_a_hand_edited_block_separately() {
    let world = world_behind(true);

    skillmirror(&world)
        .arg("status")
        .assert()
        .stdout(contains("AGENTS.md blocks: 1 edited by hand."));
}

#[test]
fn status_stays_quiet_about_blocks_that_are_current_or_missing() {
    let world = world();

    skillmirror(&world)
        .arg("status")
        .assert()
        .stdout(contains("AGENTS.md").not());
}

#[test]
fn status_json_is_not_changed_by_the_hint() {
    let world = world_behind(false);

    let document = json_of(skillmirror(&world).args(["status", "--json"]));

    assert!(document.get("projects").is_some() && document.get("summary").is_some());
    assert!(!document.to_string().contains("AGENTS"), "{document}");
}

#[test]
fn status_warns_when_the_text_cannot_be_used_and_still_reports_the_skills() {
    let world = world();
    world.vault_file("project-files/AGENTS.md", "   \n");

    skillmirror(&world)
        .arg("status")
        .assert()
        .stderr(contains("AGENTS.md:"))
        .stderr(contains("is empty"))
        .stderr(contains("doctor"));
}
